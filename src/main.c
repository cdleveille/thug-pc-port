/**
 * THUG PC Port - host entry point
 *
 * Hosts the recompiled Tony Hawk's Underground (Xbox, NTSC-U) code:
 *
 *   1. Load default.xbe from the game directory
 *   2. Map the Xbox memory layout (sections at their original VAs)
 *   3. Bring up the kernel replacement, path translation and kernel bridge
 *   4. Point the guest stack at the toolkit's stack, build the dispatch table
 *   5. Call the game's recompiled entry point
 *
 * XBE facts (tools.xbe_parser, default.xbe SHA-1 2951de95...):
 *   Title:        Tony Hawk's Underground   Title ID 0x4156002D
 *   Build:        2003-09-19, XDK 1.0.5659, "c:\skate5\Build\XBox\Final\Skate5.exe"
 *   Base / size:  0x00010000 / 0x00372480
 *   Entry point:  0x00177858
 *   .text:        0x00011000, 0x0017A8E0 bytes
 *   Code libs:    D3D, D3DX, XGRPH, DSOUND, WMADEC, BINK*, XNET, XPP
 *   Kernel:       135 imports
 *
 * Environment:
 *   THUG_GAME_DIR   directory holding default.xbe and data/, or the disc
 *                   image to unpack there (default: game/ next to the
 *                   executable, or in the tree above it; src/host/launch.h)
 *   THUG_LOG        log file, or "-" for stderr as it is (src/host/launch.h)
 *   RECOMP_*        toolkit switches; see
 *                   vendor/xboxrecomp/docs/runtime/environment-variables.md
 */

