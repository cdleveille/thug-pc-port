/* ── POSIX fault handler ───────────────────────────────────── */

/* The toolkit's AddVectoredExceptionHandler is a stub on POSIX, so the
 * project owns SIGSEGV/SIGBUS. Installed before xbox_MemoryLayoutInit so
 * any handler the toolkit adds later chains to this one. */

static void posix_fault_handler(int sig, siginfo_t *si, void *ucv)
{
    uintptr_t fault = (uintptr_t)si->si_addr;
    void *frames[48];
    int n;

    /* Trapped hardware registers: decoded and stepped over. */
    if (xbox_PosixMmioFault(ucv, fault))
        return;

    fprintf(stderr, "[CRASH] %s at addr=0x%llX",
            sig == SIGBUS ? "SIGBUS" : "SIGSEGV", (unsigned long long)fault);
#if defined(__x86_64__)
    fprintf(stderr, ", host RIP=0x%llX",
            (unsigned long long)((ucontext_t *)ucv)->uc_mcontext.gregs[REG_RIP]);
#endif
    fprintf(stderr, "\n");
    report_guest_state(fault);

    /* Host frames. With -rdynamic the lifted functions keep their names, so
     * the innermost sub_XXXXXXXX is the guest function that faulted. */
    fprintf(stderr, "  host backtrace:\n");
    n = backtrace(frames, 48);
    backtrace_symbols_fd(frames, n, STDERR_FILENO);
    thug_launch_crash_notice();

    /* Die with the original signal so a debugger or core dump sees it. */
    signal(sig, SIG_DFL);
    raise(sig);
}

static void install_fault_handler(void)
{
    /* Its own stack, so a guest stack overflow that takes the host stack with
     * it can still be reported. */
    static uint8_t altstack[64 * 1024];
    stack_t ss;
    struct sigaction sa;

    ss.ss_sp = altstack;
    ss.ss_size = sizeof(altstack);
    ss.ss_flags = 0;
    sigaltstack(&ss, NULL);

    memset(&sa, 0, sizeof(sa));
    sa.sa_sigaction = posix_fault_handler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigemptyset(&sa.sa_mask);
    sigaction(SIGSEGV, &sa, NULL);
    sigaction(SIGBUS, &sa, NULL);
}

