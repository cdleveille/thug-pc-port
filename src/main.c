/* ── Title defaults ────────────────────────────────────────── */

static void set_default(const char *name, const char *value)
{
    if (getenv(name))
        return;                     /* an explicit value always wins */
#ifdef _WIN32
    _putenv_s(name, value);
#else
    setenv(name, value, 1);
#endif
}

/* Runtime switches THUG cannot boot without. Each is opt-in in the toolkit
 * because it changes behaviour for every title. For this one they are not
 * optional (docs/BRINGUP.md, 2026-11-10):
 *
 *   RECOMP_AC97_READY  XDK DirectSound probes the AC'97 codec and drives the
 *                      APU directly; without the emulated APU, sound init
 *                      waits forever before the first asset loads.
 *   RECOMP_PB_EXEC     Someone has to consume the pushbuffer. Without the
 *                      executor no flip ever completes.
 *   RECOMP_VBLANK      D3D paces Present() on vblank interrupts; `paced` is
 *                      the 60 Hz NTSC schedule.
 *   RECOMP_USB         The emulated USB host controllers, through which XAPI
 *                      finds the pad. Host pads arrive through SDL2's
 *                      GameController API on POSIX and XInput on Windows,
 *                      which covers XInput-style pads and Steam Input.
 *   RECOMP_DISPATCH_GATE  The one-CPU gate: guest code runs only at safe
 *                      points while interrupts are delivered. XAPI's USB ISR
 *                      brackets its queue with cli/sti (0x002069BF/0x002069D0),
 *                      which lift to no-ops; without the gate a second guest
 *                      thread can enter that queue at once. Otogi, with the same
 *                      XDK USB stack, deadlocked after ~17 flips without it. */
static void thug_set_default_env(void)
{
    set_default("RECOMP_AC97_READY", "1");
    set_default("RECOMP_PB_EXEC", "1");
    set_default("RECOMP_VBLANK", "paced");
    set_default("RECOMP_USB", "1");
    /* The keyboard as player one's pad, for the menus (src/host/controls.h). */
    set_default("RECOMP_KEYBOARD", "1");
    set_default("RECOMP_DISPATCH_GATE", "1");
    /* RECOMP_ASYNC_IO: a read on an asynchronous handle returns
     * STATUS_PENDING, as the console's DVD/HDD path does. THUG's stream
     * start (sub_00033940) takes an immediate TRUE from ReadFile as "stream
     * finished" without counting the bytes, so every audio stream looked
     * empty and the main-menu load waited for it forever (sub_00106EE0). */
    set_default("RECOMP_ASYNC_IO", "1");
    /* RECOMP_CONTIG_AVOID_IMAGE: contiguous allocations stay out of the
     * image's physical range. THUG's stream buffer is a static in .data
     * (0x0024E7F0); with a contiguous page handed out at the same physical
     * number the APU resolved the stream's address into the window, and
     * voice lists came back with garbage handles (0x1ACD, 0x4A8B...). */
    set_default("RECOMP_CONTIG_AVOID_IMAGE", "1");
    /* RECOMP_HEAP_RECLAIM: MmFreeContiguousMemory / NtFreeVirtualMemory give
     * memory back. Without it nothing is ever freed (allocs=2027 frees=0 by
     * the main menu); loading a level after the menus exhausted the 64 MB
     * contiguous arena, a texture failed to allocate and the title called
     * exit() -- on the console it never runs out, because it frees the menu
     * first. */
    set_default("RECOMP_HEAP_RECLAIM", "1");
    /* GPU renderer: face culling off. The renderer's culling winding is wrong
     * for THUG (every other triangle of the 3D meshes vanished); drawing both
     * faces costs nothing measurable on a desktop GPU and the depth test hides
     * back faces. TODO: fix the winding and turn this back off. */
    set_default("RECOMP_GL_NO_CULL", "1");
    /* Widescreen: the dashboard's 16:9 setting, which THUG supports natively.
     * It then sets D3DPRESENTFLAG_WIDESCREEN, widens its field of view (Hor+)
     * and lays its HUD out for 16:9, rendering anamorphic into its 640x480
     * surfaces; the GPU renderer gives the x axis the extra resolution and
     * presents the chosen aspect. On for any aspect wider than 4:3
     * (aspect_ratio, THUG_ASPECT): 16:10 runs the same widescreen mode, and
     * recomp_manual.c gives the game's camera the exact aspect. */
    if (thug_aspect_is_wide(g_thug_settings.aspect))
        set_default("RECOMP_WIDESCREEN", "1");
#if defined(_WIN32)
    /* RECOMP_WIN_PLACEHOLDER: reserve the guest's whole 4 GB window in one
     * placeholder (VirtualAlloc2) and carve RAM, the contiguous window at
     * 0x80000000 and the apertures out of it. The GPU renderer opens its
     * window and loads the GL driver before the guest maps its memory, so
     * the driver's allocations can otherwise sit where the contiguous window
     * belongs. The POSIX side reserves the whole window unconditionally for
     * the same reason (docs/NOTES.md, "Toolkit changes"). */
    set_default("RECOMP_WIN_PLACEHOLDER", "1");
#endif
}

/* ── Boot ──────────────────────────────────────────────────── */

static int thug_guest_main(void)
{
    void *xbe_data = NULL;
    size_t xbe_size = 0;

    fprintf(stderr, "=== Tony Hawk's Underground - static recompilation ===\n");

    fprintf(stderr, "[thug] loading %s\n", g_xbe_path);
    if (!load_xbe(g_xbe_path, &xbe_data, &xbe_size)) {
        fprintf(stderr, "[thug] failed to load %s\n", g_xbe_path);
        return 1;
    }
    fprintf(stderr, "[thug] XBE loaded: %zu bytes\n", xbe_size);

    if (!xbox_MemoryLayoutInit(xbe_data, xbe_size)) {
        fprintf(stderr, "[thug] xbox_MemoryLayoutInit failed: the guest address "
                        "range may be unavailable\n");
        free(xbe_data);
        return 1;
    }
    g_xbox_mem_offset = xbox_GetMemoryOffset();
    fprintf(stderr, "[thug] Xbox memory mapped, offset 0x%llX\n",
            (unsigned long long)g_xbox_mem_offset);
    thug_keyboard_controls_guest_mapped(g_xbox_mem_offset);   /* Escape: START or B */

    /* D3D's GPU-progress fence. XDK D3D (5659) keeps its device pointer at
     * THUG_D3D_DEVICE_PTR; device+0x2C is the fence it has submitted and
     * device+0x30 points at the word the GPU writes as it consumes the
     * pushbuffer. sub_00190900 spins until that word passes its target, so
     * without a GPU behind it the first Present() that changes display mode
     * waits forever. The NV2A poll thread copies submitted into consumed.
     *
     * THUG_FENCE_SEMAPHORE=1 (experimental) has the executor write the word
     * from D3D's own semaphore releases instead, so it reports what has really
     * been executed. D3D then sees a GPU that is behind and, past 0x2400 bytes,
     * patches a software-method wake-up into the pushbuffer and waits on the
     * GPU's fence latch for it -- an interrupt this runtime does not deliver --
     * so the title hangs at its save check. Kept for whoever implements it. */
    if (getenv("THUG_FENCE_SEMAPHORE") && *getenv("THUG_FENCE_SEMAPHORE") == '1') {
        xbox_Nv2aTrackFence(THUG_D3D_DEVICE_PTR, 0x2C, 0x30);
        nv2a_pb_semaphore_from_fence_word(1);
    } else {
        xbox_Nv2aMirrorFence(THUG_D3D_DEVICE_PTR, 0x2C, 0x30);
    }

    /* Controllers: the USB host controllers XAPI enumerates pads through.
     * Inert unless RECOMP_USB is set (a default, see thug_set_default_env). */
    xbox_OhciInit();

    /* Only useful together with the register traps RECOMP_AC97_READY arms. */
    if (getenv("RECOMP_AC97_READY")) {
        g_apu_state = mcpx_apu_init_standalone((uint8_t *)xbox_GetMemoryBase());
        fprintf(stderr, "[thug] emulated APU %s\n",
                g_apu_state ? "up" : "FAILED to initialise");
    }

    xbox_kernel_init();
    xbox_path_init(g_game_dir, NULL);
    xbox_kernel_bridge_init();

    g_esp = XBOX_STACK_TOP;

    if (!recomp_dispatch_init())
        fprintf(stderr, "[thug] flat dispatch unavailable; "
                        "indirect calls will use the binary search\n");

    /* Inert unless RECOMP_WATCHDOG_SECS is set; must run on the guest thread. */
    xbox_WatchdogStart();

    fprintf(stderr, "[thug] entering guest at 0x%08X, esp=0x%08X\n",
            THUG_ENTRY_POINT, g_esp);
    xbe_entry_point();
    fprintf(stderr, "[thug] guest returned\n");

    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe_data);
    return 0;
}

int main(int argc, char **argv)
{
    /* The arguments and environment as the player started us, before
     * start-up adds to them: what a restart from the overlay runs with. */
    thug_restart_init(argc, argv);

    /* Unbuffered so boot progress survives a crash or hang. */
    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);

    /* The log goes to a file unless the caller redirected stderr. */
    thug_launch_log_setup();

#if !defined(_WIN32)
    /* The GL driver's own worker thread (see nv2a_pb_gl_init), asked for
     * before anything can load the driver: the first-launch progress window
     * may, through SDL. */
    if (!getenv("THUG_GL_NO_DRIVER_THREAD")) {
        setenv("__GL_THREADED_OPTIMIZATIONS", "1", 0);
        setenv("mesa_glthread", "true", 0);
    }
#endif

    /* The player's saved settings (F1 overlay), exported as the THUG_*
     * variables the rest of start-up reads; a variable already set wins. */
    thug_settings_load();
    thug_set_default_env();
    thug_settings_apply_audio_input();   /* master volume, vibration strength */
    thug_keyboard_controls_install();    /* Enter/Space A, Esc START or B, ... */

    /* The game's files: found, or unpacked from the disc image and checked;
     * otherwise the player is told what is missing. */
    if (!thug_launch_prepare(g_game_dir, sizeof g_game_dir))
        return 1;

#if defined(__linux__)
    /* THUG_DEBUG_ATTACH: let any debugger attach (Yama ptrace_scope 1 allows
     * only a parent otherwise). Every lifted function is a host symbol, so
     * `gdb -p <pid> -batch -ex "thread apply all bt"` at a hang reads as the
     * guest call chain -- exact, where the watchdog's stack scan also picks
     * up stale return addresses. Off by default. */
    if (getenv("THUG_DEBUG_ATTACH"))
        prctl(PR_SET_PTRACER, PR_SET_PTRACER_ANY, 0, 0, 0);
#endif

    snprintf(g_xbe_path, sizeof(g_xbe_path), "%s/default.xbe", g_game_dir);

    install_fault_handler();

    /* The GPU renderer (src/gpu): SDL video and the GL context are created
     * here, on the main thread, before the window loop takes it over; the
     * executor's poll thread only makes the context current to draw. Returns
     * 0 -- and the CPU rasteriser carries on -- with RECOMP_PB_GL=0 or no
     * display. */
    if (nv2a_pb_gl_init()) {
        fprintf(stderr, "[thug] GPU renderer active (RECOMP_PB_GL=0 for the CPU rasteriser)\n");
        /* The renderer opened the game's window: pump it here, run the guest
         * on a pthread. Headless, there is no window and this calls through. */
        if (nv2a_pb_gl_window())
            return thug_host_window_main(thug_guest_main);
    }

#if defined(_WIN32)
    /* Headless, or the CPU rasteriser: the guest on this thread (its stack is
     * the executable's 8 MB reserve, as a Linux main thread's). */
    return thug_guest_main();
#else
    /* CPU rasteriser: with RECOMP_FB_WINDOW set this opens the framebuffer
     * window on the main thread and runs the guest on a pthread; otherwise it
     * calls straight through. */
    return xbox_HostWindowMain(thug_guest_main);
#endif
}

/* ── XBE loading ───────────────────────────────────────────── */

static bool load_xbe(const char *path, void **out_data, size_t *out_size)
{
    FILE *f = fopen(path, "rb");
    long size;
    void *data;

    if (!f)
        return false;
    fseek(f, 0, SEEK_END);
    size = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (size <= 0) {
        fclose(f);
        return false;
    }
    data = malloc((size_t)size);
    if (!data || fread(data, 1, (size_t)size, f) != (size_t)size) {
        free(data);
        fclose(f);
        return false;
    }
    fclose(f);
    *out_data = data;
    *out_size = (size_t)size;
    return true;
}
