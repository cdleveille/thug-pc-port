/* XAPI media check (XDK 5659), called once at startup from sub_00178D5F.
 *
 * The retail check authenticates the physical disc: MODE SENSE page 0x3E,
 * then -- because THUG's certificate sets the flag at cert+0x1D8 -- READ DVD
 * STRUCTURE for the 1636-byte security sector, which sub_00178ACE checks
 * against the certificate's title ID, a SHA-1 digest and an RSA signature
 * under the kernel's public key. A port running from extracted files has no
 * drive and no security sector, so the check can only fail, and on failure
 * the title reboots to the dashboard (HalReturnToFirmware with launch data
 * LDT_LAUNCH_DASHBOARD).
 *
 * Original: cdecl, no arguments, plain `ret`; returns an NTSTATUS in eax. */
void sub_00178B85(void)
{
    g_eax = 0;      /* STATUS_SUCCESS: media verified */
    g_esp += 4;     /* pop the guest return address (`ret`) */
}

/* Host monotonic clock, in seconds. */
#if defined(_WIN32)
#include <windows.h>
static double host_seconds(void)
{
    static LARGE_INTEGER freq;
    LARGE_INTEGER now;
    if (!freq.QuadPart)
        QueryPerformanceFrequency(&freq);
    QueryPerformanceCounter(&now);
    return (double)now.QuadPart / (double)freq.QuadPart;
}
#else
#include <time.h>
static double host_seconds(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec * 1e-9;
}
#endif
#include <stdlib.h>

/* The engine's per-frame frame-length update (Neversoft's Tmr), called once
 * per game frame from the main loop (call at 0x000309F2).
 *
 * The original averages the vblanks between the last four swaps -- the D3D
 * swap callback (sub_00173ED0) records each one in the ring at 0x35F040 --
 * clamping each to 1..4. The result, in vblanks, goes to 0x35F030 (float,
 * at least 1.0) and the unclamped average to 0x35F038 (double).
 * FrameLength() (sub_001741F0) is slomo / refresh * [0x35F030], and every
 * dt-scaled system (skater physics, animation, the camera) runs on it.
 *
 * A frame shorter than a vblank therefore still counted as a whole one: at
 * 144 fps the game ran 2.4 times too fast. Here the same two values are the
 * real host time between frames, in vblanks of the title's own refresh rate
 * (0x2408B0), averaged over four frames as before and capped at four vblanks
 * as before, with no floor of one. THUG_VBLANK_TIMING=1 restores the
 * original whole-vblank arithmetic (so does the overlay's switch).
 *
 * Original: cdecl, no arguments, plain `ret`; returns the average in xmm0. */
void sub_00173F80(void)
{
    static double last, hist[4] = { 1.0, 1.0, 1.0, 1.0 };
    static unsigned n;
    double avg, raw;
    float refresh;

    /* THUG_VBLANK_TIMING, or the overlay's "Original 60 Hz timing", read
     * every frame so the switch takes effect at once. */
    if (g_thug_settings.vblank_timing) {
        last = 0.0;                     /* the real clock restarts cleanly */
        uint32_t i, clamped = 0, sum = 0;
        for (i = 0; i < 4; i++) {
            uint32_t d = MEM32(0x35F040 + i * 4);
            sum += d;
            clamped += d < 1 ? 1 : (d > 4 ? 4 : d);
        }
        avg = clamped * 0.25;
        raw = sum * 0.25;
    } else {
        double now = host_seconds(), dt;
        refresh = MEMF(0x2408B0);
        if (!(refresh > 1.0f && refresh < 1000.0f))
            refresh = 60.0f;
        dt = last > 0.0 ? (now - last) * refresh : 1.0;
        last = now;
        if (!(dt > 0.01))
            dt = 0.01;              /* 6000 fps: a floor, not a frame rate */
        if (dt > 4.0)
            dt = 4.0;               /* a load or a hitch: as the original */
        hist[n++ & 3] = dt;
        avg = raw = (hist[0] + hist[1] + hist[2] + hist[3]) * 0.25;
    }
    MEMF(0x35F030) = (float)avg;
    MEMD(0x35F038) = raw;
    g_xmm0.f[0] = (float)avg;
    g_esp += 4;                     /* `ret` */
}

/* The screen's aspect and the camera's field of view, as the engine hands
 * them out (Neversoft's Nx screen settings).
 *
 * The script command SetScreen (sub_00117740) stores the aspect at 0x2B33DC
 * (sub_0008F820) and, from its angle, the ratio tan(angle/2) /
 * tan(base/2) at 0x229C2C (sub_0008FB50; the base, camera_fov, is 72). Every
 * reader goes through these two getters: the viewport's aspect
 * (sub_0008FDA0), the screen-to-3D helper (sub_000C5960), and the cameras'
 * field of view (sub_0009ADA0 and its siblings, which cache the result in
 * the camera at +0xA4 when its FOV is set). The scripts know two shapes:
 * standard (1.33333, angle 72) and widescreen or letterbox (1.77778, angle
 * 88.18, which is Hor+: the same vertical view as 4:3).
 *
 * The port offers 16:10 too (aspect_ratio). For any aspect wider than 4:3
 * the game runs its widescreen mode (main.c sets the dashboard flag), and
 * these return the chosen aspect and the game's ratio scaled by
 * chosen / stored aspect, which keeps whatever vertical view the game set:
 * 16:9 gives exactly the game's own values, 16:10 an 82.2-degree view. At
 * 4:3 they return the stored values, so the game's letterboxed cutscenes
 * stay as they were. The aspect is read each call, and in play the cameras
 * ask for the ratio a few hundred times a second, so a change in the overlay
 * shows within a frame.
 *
 * Originals: cdecl, no arguments, `fld dword [addr]; ret`. */
static float screen_aspect_chosen(float stored)
{
    float a = g_thug_settings.aspect;
    return thug_aspect_is_wide(a) ? a : stored;
}

static void fpu_push(double v)
{
    g_fp_top = (g_fp_top + 7) & 7;
    g_fp_stack[g_fp_top] = v;
}

/* The screen aspect. */
void sub_0008F830(void)
{
    fpu_push(screen_aspect_chosen(MEMF(0x2B33DC)));
    g_esp += 4;
}

/* The field-of-view ratio. */
void sub_0008F860(void)
{
    float stored = MEMF(0x2B33DC), ratio = MEMF(0x229C2C);
    float a = screen_aspect_chosen(stored);

    if (stored > 0.5f && a != stored)
        ratio *= a / stored;
    fpu_push(ratio);
    g_esp += 4;
}

