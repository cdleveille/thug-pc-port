/* XAPI media check (XDK 5659), called once at startup from sub_00178D5F.
 *
 * The retail check authenticates the physical disc: MODE SENSE page 0x3E,
 * then -- because THUG's certificate sets the flag at cert+0x1D8 -- READ DVD
 * STRUCTURE for the 1636-byte security sector, which sub_00178ACE checks
 * against the certificate's title ID, a SHA-1 digest and an RSA signature
 * under the kernel's public key. A port running from extracted files has no
 * drive and no security sector, so the check can only fail, and on failure
 * the title reboots to the dashboard (HalReturnToFirmware with launch data
 * LDT_LAUNCH_DASHBOARD).
 *
 * Original: cdecl, no arguments, plain `ret`; returns an NTSTATUS in eax. */
void sub_00178B85(void)
{
    g_eax = 0;      /* STATUS_SUCCESS: media verified */
    g_esp += 4;     /* pop the guest return address (`ret`) */
}

