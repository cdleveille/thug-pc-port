#!/usr/bin/env python3
"""Embed a PNG as raw RGBA in a C source file: the game window's icon.

Usage: embed_icon.py <icon.png> <max size> <out.c>

The build runs this (CMakeLists.txt), so the PNG stays the one source of the
icon: replace thug.png and the next build carries the new one. SDL2 reads
only BMP by itself, and a PNG library is not worth a dependency for one
image, so the decoding happens here, with nothing but the standard library.

Handles what an icon editor writes: 8-bit greyscale, RGB, palette (with
tRNS), greyscale + alpha and RGBA, not interlaced. Larger than <max size>,
the image is shrunk by an integer factor, averaging each block with its
alpha (premultiplied, so transparent pixels do not darken the edges).
"""
import struct
import sys
import zlib


def fail(msg):
    sys.exit("embed_icon.py: " + msg)


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        fail("%s is not a PNG" % path)
    pos, idat, plte, trns = 8, b"", None, None
    w = h = depth = ctype = inter = None
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, inter = struct.unpack(">IIBBBBB", body)
        elif kind == b"PLTE":
            plte = body
        elif kind == b"tRNS":
            trns = body
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
    if depth != 8 or inter != 0:
        fail("only 8-bit, non-interlaced PNGs (this one: depth %s, interlace %s)"
             % (depth, inter))
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}.get(ctype)
    if channels is None:
        fail("unknown PNG colour type %d" % ctype)
    raw = zlib.decompress(idat)
    stride = w * channels
    rows, prev = [], bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - channels] if i >= channels else 0
            b = prev[i]
            c = prev[i - channels] if i >= channels else 0
            if f == 1:
                line[i] = (line[i] + a) & 0xFF
            elif f == 2:
                line[i] = (line[i] + b) & 0xFF
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pred) & 0xFF
            elif f != 0:
                fail("bad PNG filter %d" % f)
        rows.append(line)
        prev = line
    rgba = bytearray(w * h * 4)
    for y, line in enumerate(rows):
        for x in range(w):
            o = (y * w + x) * 4
            if ctype == 6:
                rgba[o:o + 4] = line[x * 4:x * 4 + 4]
            elif ctype == 2:
                rgba[o:o + 3] = line[x * 3:x * 3 + 3]
                rgba[o + 3] = 255
            elif ctype == 0:
                rgba[o:o + 3] = bytes([line[x]] * 3)
                rgba[o + 3] = 255
            elif ctype == 4:
                rgba[o:o + 3] = bytes([line[x * 2]] * 3)
                rgba[o + 3] = line[x * 2 + 1]
            else:                                   # palette
                k = line[x]
                rgba[o:o + 3] = plte[k * 3:k * 3 + 3]
                rgba[o + 3] = trns[k] if trns and k < len(trns) else 255
    return w, h, rgba


def shrink(w, h, rgba, limit):
    k = 1
    while w // k > limit or h // k > limit:
        k += 1
    if k == 1:
        return w, h, rgba
    ow, oh = w // k, h // k
    out = bytearray(ow * oh * 4)
    for y in range(oh):
        for x in range(ow):
            r = g = b = a = 0
            for yy in range(y * k, y * k + k):
                for xx in range(x * k, x * k + k):
                    o = (yy * w + xx) * 4
                    pa = rgba[o + 3]
                    r += rgba[o] * pa
                    g += rgba[o + 1] * pa
                    b += rgba[o + 2] * pa
                    a += pa
            o = (y * ow + x) * 4
            if a:
                out[o:o + 3] = bytes([(r + a // 2) // a, (g + a // 2) // a, (b + a // 2) // a])
            out[o + 3] = (a + k * k // 2) // (k * k)
    return ow, oh, out


def main():
    if len(sys.argv) != 4:
        fail("usage: embed_icon.py <icon.png> <max size> <out.c>")
    w, h, rgba = read_png(sys.argv[1])
    w, h, rgba = shrink(w, h, rgba, int(sys.argv[2]))
    with open(sys.argv[3], "w") as f:
        f.write("/* Generated by scripts/embed_icon.py from %s: do not edit. */\n"
                % sys.argv[1].replace("\\", "/").split("/")[-1])
        f.write("const int thug_icon_w = %d, thug_icon_h = %d;\n" % (w, h))
        f.write("const unsigned char thug_icon_rgba[%d] = {\n" % len(rgba))
        for i in range(0, len(rgba), 24):
            f.write("    " + ", ".join(str(v) for v in rgba[i:i + 24]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
