#!/usr/bin/env bash
# Runs inside the release container (scripts/release/Dockerfile), started by
# scripts/release.sh with the repository mounted at its own path: compiles
# the game against Ubuntu 22.04's glibc, checks what the executable needs
# from a player's system, and lays out the release in build/release/.
#
# Environment (scripts/release.sh sets both):
#   THUG_VERSION  the version in the release's name
#   JOBS          parallel compile jobs
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

VERSION="${THUG_VERSION:?THUG_VERSION is not set (run scripts/release.sh)}"
JOBS="${JOBS:-$(nproc)}"

# The oldest glibc the release runs on: the container's (Ubuntu 22.04).
# Moving the base image moves it, and drops every distribution in between,
# so the check below makes that a decision rather than a side effect.
GLIBC_FLOOR=2.35
# The libraries the executable may name. Everything else it uses (SDL's X11,
# Wayland, sound and udev libraries, the GL driver) is loaded at run time and
# is optional; these are on every glibc system (the last three are part of
# libc itself since glibc 2.34).
ALLOWED_NEEDED="libc.so.6 libm.so.6 ld-linux-x86-64.so.2 libpthread.so.0 libdl.so.2 librt.so.1"

BUILD=build/release-build
OUT=build/release
NAME="thug-pc-port-$VERSION-linux-x86_64"
STAGE="$OUT/$NAME"

step() { printf '\n==> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

step "configuring $BUILD: $("$CC" --version | head -1); $(ldd --version | head -1)"
cmake -S . -B "$BUILD" -G Ninja \
  -DCMAKE_BUILD_TYPE=RelWithDebInfo \
  -DCMAKE_EXE_LINKER_FLAGS=-Wl,--build-id=sha1 \
  -DTHUG_REQUIRE_SDL_BACKENDS=ON

step "compiling ($JOBS jobs)"
cmake --build "$BUILD" --target thug -j "$JOBS"
BIN="$BUILD/bin/thug"

step "checking what the executable needs from the system"
fail=0
# Ubuntu 22.04's binutils predate some of clang 23's DWARF 5 and say so at
# length; the dynamic sections read here are unaffected. An empty answer is
# a failure, not a pass.
symbols=$(objdump -T "$BIN" 2>/dev/null) || die "objdump could not read $BIN"
newest=$(grep -oE 'GLIBC_[0-9]+(\.[0-9]+)+' <<<"$symbols" | sed 's/^GLIBC_//' | sort -uV | tail -1 || true)
[[ -n $newest ]] || die "found no glibc symbol versions in $BIN"
if [[ $(printf '%s\n%s\n' "$newest" "$GLIBC_FLOOR" | sort -V | tail -1) != "$GLIBC_FLOOR" ]]; then
  printf '  needs glibc %s, newer than the release supports (%s):\n' "$newest" "$GLIBC_FLOOR" >&2
  grep -F "GLIBC_$newest" <<<"$symbols" | awk '{ print "    " $NF }' | sort -u >&2
  fail=1
else
  echo "  glibc $newest or newer (the release supports $GLIBC_FLOOR)"
fi
if grep -qE 'GLIBCXX_|CXXABI_' <<<"$symbols"; then
  echo "  the C++ runtime is linked as a shared library; it must be static" >&2
  fail=1
fi
needed=$(readelf -d "$BIN" 2>/dev/null | sed -n 's/.*(NEEDED).*\[\(.*\)\]$/\1/p')
[[ -n $needed ]] || die "readelf found no libraries in $BIN"
for lib in $needed; do
  if [[ " $ALLOWED_NEEDED " != *" $lib "* ]]; then
    echo "  links $lib, which a player's system may not have" >&2
    fail=1
  fi
done
echo "  libraries: $(echo $needed)"
[[ $fail -eq 0 ]] || die "the executable would not run everywhere the release says it does"

step "packaging $STAGE"
rm -rf "$STAGE"
rm -f "$OUT/$NAME.tar.gz" "$OUT/$NAME.tar.gz.sha256" "$OUT/$NAME.debug"
mkdir -p "$STAGE/game" "$STAGE/licenses"

# The debug info stays here, beside the release, for reading players' crash
# reports (addr2line -e, or gdb's symbol-file). The shipped executable keeps
# its symbol tables, so the crash reporter still names the function.
objcopy --only-keep-debug "$BIN" "$OUT/$NAME.debug"
objcopy --strip-debug --add-gnu-debuglink="$OUT/$NAME.debug" "$BIN" "$STAGE/thug"
chmod 755 "$STAGE/thug"

sed "s/@VERSION@/$VERSION/g" scripts/release/README.txt > "$STAGE/README.txt"
cp scripts/release/game-README.txt "$STAGE/game/README.txt"

L="$STAGE/licenses"
cp vendor/SDL/LICENSE.txt                    "$L/SDL2.txt"
cp vendor/SDL/src/hidapi/LICENSE.txt         "$L/SDL2-hidapi.txt"
cp vendor/SDL/src/hidapi/LICENSE-bsd.txt     "$L/SDL2-hidapi-bsd.txt"
cp vendor/SDL/src/video/yuv2rgb/LICENSE      "$L/SDL2-yuv2rgb.txt"
cp vendor/imgui/LICENSE.txt                  "$L/dear-imgui.txt"
cp vendor/xboxrecomp/LICENSE                 "$L/xboxrecomp.txt"
cp vendor/xboxrecomp/NOTICE                  "$L/xboxrecomp-NOTICE.txt"
cp vendor/xboxrecomp/LICENSES/LGPL-2.1.txt   "$L/LGPL-2.1.txt"
cp /usr/share/common-licenses/Apache-2.0     "$L/Apache-2.0.txt"
cat > "$L/glad.txt" <<'EOF'
The OpenGL loader was generated by glad 2.0.8
(https://github.com/Dav1dde/glad).

SPDX-License-Identifier: (WTFPL OR CC0-1.0) AND Apache-2.0

The generated code is under WTFPL or CC0-1.0, at your choice. The parts
taken from the Khronos OpenGL API registry are under the Apache License 2.0,
whose text is in Apache-2.0.txt.
EOF

tar -C "$OUT" --sort=name --owner=0 --group=0 --numeric-owner \
    -czf "$OUT/$NAME.tar.gz" "$NAME"
(cd "$OUT" && sha256sum "$NAME.tar.gz" > "$NAME.tar.gz.sha256")

step "done"
du -h "$STAGE/thug" "$OUT/$NAME.tar.gz" "$OUT/$NAME.debug" | sed 's/^/  /'
